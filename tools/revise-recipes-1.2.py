def label(k,case='acc'):
 assert k in CASES, ('Missing reviewed case',k)
 return CASES[k][0 if case=='acc' else 1]

class Method:
 def __init__(self, r):
  self.r=r; self.items={i['id']:i for i in r['ingredients']}; self.used=set(); self.steps=[]; self.usage=[]
 def has(self,k): return k in self.items
 def step(self,text,*ids):
  assert text and set(ids)<=self.items.keys(), (self.r['name'],ids,self.items.keys())
  self.steps.append(text); self.used.update(ids); self.usage.append(list(ids))
 def prep(self,ids):
  chosen=[k for k in ids if self.has(k)]
  if chosen: self.step(' '.join((FRUIT|VEG)[k] for k in chosen),*chosen)
  return chosen
 def add(self,k,q,unit='г',note=None):
  if self.has(k): return
  name,group={'water':('Вода','Прочее'),'salt':('Соль','Бакалея'),'vanilla':('Ванильный сахар','Бакалея')}[k]
  i={'id':k,'name':name,'quantity':q,'unit':unit,'group':group,'note':note,'staple':k in ('water','salt')}
  self.r['ingredients'].append(i); self.items[k]=i
 def season(self):
  keys=[k for k in ('salt','blackpepper') if self.has(k)]
  if keys: self.step('В конце добавьте '+('соль и молотый чёрный перец' if len(keys)==2 else 'соль' if keys[0]=='salt' else 'молотый чёрный перец')+' по вкусу.',*keys)
 def finish(self):
  unused=set(self.items)-self.used
  assert not unused, (self.r['name'],'unused',unused)
  assert len(self.steps)>=4, (self.r['name'],self.steps)
  self.r['steps']=self.steps
  self.r['methodVersion']=2
  return self.usage

